#!/usr/bin/env bash
# Builds the RTI ZRP-6 Control4 driver (rti_zrp6.c4z).
#
#   ./build.sh            stage, validate and package build/rti_zrp6.c4z
#   ./build.sh --stage    stage and validate only (CI packages with the
#                         snap-one/drivers-driverpackager action instead)
#
# Staging assembles build/stage/ from driver/: src/*.lua is concatenated into
# driver.lua and syntax checked, www/ is copied, the Composer tabs (Remote
# Buttons, Control) are built from driver/ui/ into www/html/ (esbuild, see
# README), and
# driver.xml is stamped with a version and date. Nothing under driver/ is
# modified.
#
# Needs node + npm (the UI build installs the pinned esbuild from
# package-lock.json on first use). Packaging also needs Python 3 with lxml
# (pip3 install lxml) and git; it clones snap-one/drivers-driverpackager into
# tools/ on first use.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

MODE="${1:-package}"
SRC=driver
STAGE=build/stage
PROJ=rti_zrp6.c4zproj

rm -rf "$STAGE"
mkdir -p "$STAGE"

# ---------------------------------------------------------------------------
# 1. driver.lua = src/*.lua
# ---------------------------------------------------------------------------
for page in index control; do
  if ! grep -q "file=\"html/$page.html\"" "$SRC/driver.xml"; then
    echo "error: driver.xml is missing the <tab> for html/$page.html" >&2
    exit 1
  fi
done

echo "Concatenating $SRC/src -> $STAGE/driver.lua"
{
  echo '-- RTI ZRP-6 I/O box driver for Control4'
  echo '-- AUTO-GENERATED by build.sh - edit driver/src/ instead.'
  echo '---@diagnostic disable: undefined-global'
  for f in "$SRC"/src/*.lua; do
    echo
    cat "$f"
  done
} > "$STAGE/driver.lua"
echo "  OK  $(wc -l < "$STAGE/driver.lua" | tr -d ' ') lines"

# ---------------------------------------------------------------------------
# 2. Syntax check. Controllers run it under LuaJIT (Lua 5.1 syntax);
#    luac of any 5.x catches most mistakes, luajit catches 5.1-isms.
# ---------------------------------------------------------------------------
echo "Validating Lua"
luac -p "$STAGE/driver.lua"
echo "  OK  luac ($(luac -v 2>&1 | head -1))"
if command -v luajit >/dev/null 2>&1; then
  luajit -e "assert(loadfile('$STAGE/driver.lua'))"
  echo "  OK  luajit"
fi

# ---------------------------------------------------------------------------
# 3. Stage the rest and stamp driver.xml
# ---------------------------------------------------------------------------
cp "$SRC/driver.xml" "$SRC/$PROJ" "$STAGE/"
cp -R "$SRC/www" "$STAGE/www"

echo "Building the Composer tabs (driver/ui -> www/html/index.html, control.html)"
if [[ ! -x node_modules/.bin/esbuild ]]; then
  npm ci --no-audit --no-fund --silent
fi
node "$SRC/ui/build.mjs" "$STAGE/www/html"

BUILD_DATE=$(date +"%m/%d/%Y %H:%M")
VERSION=$(git rev-list --count HEAD 2>/dev/null || echo "1")
python3 - "$STAGE/driver.xml" "$VERSION" "$BUILD_DATE" <<'EOF'
import re, sys
path, version, date = sys.argv[1:4]
s = open(path, encoding='utf-8').read()
s = re.sub(r'<version>[^<]*</version>', '<version>%s</version>' % version, s, count=1)
s = re.sub(r'<modified>[^<]*</modified>', '<modified>%s</modified>' % date, s, count=1)
open(path, 'w', encoding='utf-8').write(s)
EOF
echo "Stamped driver.xml: version=${VERSION} modified=${BUILD_DATE}"

if [[ "$MODE" == "--stage" ]]; then
  echo "Staged in $STAGE"
  exit 0
fi

# ---------------------------------------------------------------------------
# 4. Package with snap-one driverpackager (dp3)
# ---------------------------------------------------------------------------
DP3="tools/driverpackager/dp3/driverpackager.py"
if [[ ! -f "$DP3" ]]; then
  echo "Cloning snap-one/drivers-driverpackager into tools/driverpackager"
  mkdir -p tools
  git clone --depth=1 https://github.com/snap-one/drivers-driverpackager tools/driverpackager
fi

echo "Running driverpackager"
python3 "$DP3" -v "$STAGE" build "$PROJ"
C4Z="build/rti_zrp6.c4z"
echo
echo "Built: $C4Z ($(wc -c < "$C4Z" | tr -d ' ') bytes)"
